#!/usr/bin/env python3
"""Generates the Unicode tables of the passphrase normalisation (NFC).

  python3 tool/passphrase_nfc.py            # writes lib/backup/data/nfc_table.dart
  python3 tool/passphrase_nfc.py --check    # exit 1 when that file is stale
  python3 tool/passphrase_nfc.py --stdout   # prints the file instead
  python3 tool/passphrase_nfc.py --normalize < strings.json

Backup and sync passphrases are put in Unicode Normalization Form C
(composed) before Argon2id, so "é" typed as one character and "e" followed
by a combining acute accent (what some keyboards and macOS input produce)
give the same key. The app has no Unicode library, so this script writes
the data `lib/backup/data/passphrase_nfc.dart` needs, from Python's
`unicodedata`, as const Dart maps:

- `nfcCombiningClasses`: the canonical combining class of every combining
  mark in the covered blocks (the marks used with Latin, Greek, Cyrillic
  and Vietnamese letters, and the kana voicing marks);
- `nfcDecompositions`: the canonical decomposition (one level) of every
  letter (and the few symbols such as "≠") of the covered blocks that has
  one;
- `nfcCompositions`: starter -> mark -> composed letter, for the pairs NFC
  composes (not the composition exclusions).

Hangul syllables are composed and decomposed by arithmetic in Dart, so they
need no table. Other scripts' characters pass through unchanged.

Only characters already assigned in Unicode 3.2 (`unicodedata.ucd_3_2_0`)
are listed: Unicode's stability policy fixes their decompositions and
combining classes, and characters added later never compose (they are
composition exclusions), so every Python 3 generates the same table. A
test (test/backup/data/passphrase_nfc_test.dart) checks that the committed
file matches a fresh generation and compares the Dart normalisation with
Python's on generated strings (`--normalize` reads a JSON array of strings
on stdin and prints their NFC forms as a JSON array).

Do not widen the covered blocks lightly: a passphrase with characters that
become normalised derives another key, and only the passphrase exactly as
typed is tried as well (see BackupCodec).
"""

from __future__ import annotations

import json
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "lib" / "backup" / "data" / "nfc_table.dart"

# Blocks whose combining marks are listed (with their combining class).
MARK_BLOCKS = [
    (0x0300, 0x036F),  # Combining Diacritical Marks
    (0x0483, 0x0489),  # Cyrillic combining marks
    (0x1DC0, 0x1DFF),  # Combining Diacritical Marks Supplement
    (0x20D0, 0x20FF),  # Combining Diacritical Marks for Symbols
    (0x3099, 0x309A),  # Kana voicing marks
    (0xFE20, 0xFE2F),  # Combining Half Marks
]

# Blocks whose letters' decompositions (and compositions) are listed.
LETTER_BLOCKS = [
    (0x00C0, 0x024F),  # Latin-1 letters, Latin Extended-A and -B
    (0x0300, 0x036F),  # marks that decompose to other marks
    (0x0370, 0x03FF),  # Greek and Coptic
    (0x0400, 0x04FF),  # Cyrillic
    (0x0500, 0x052F),  # Cyrillic Supplement
    (0x1E00, 0x1EFF),  # Latin Extended Additional (Vietnamese)
    (0x1F00, 0x1FFF),  # Greek Extended
    (0x2126, 0x212B),  # Ohm, Kelvin and Angstrom signs
    (0x2190, 0x22FF),  # arrows and operators with a slash (≠, ∉, ...)
    (0x3040, 0x30FF),  # Hiragana and Katakana
]

HEADER = """\
// GENERATED by tool/passphrase_nfc.py from Python's unicodedata: do not
// edit. Run `python3 tool/passphrase_nfc.py` to regenerate it.

// The data of passphrase_nfc.dart: see the script for what is covered.
"""


def _assigned(code: int) -> bool:
    """Assigned in Unicode 3.2 (stable data in every Python 3)."""
    return unicodedata.ucd_3_2_0.category(chr(code)) != "Cn"


def _codes(blocks: list[tuple[int, int]]) -> list[int]:
    return [
        code
        for start, end in blocks
        for code in range(start, end + 1)
        if _assigned(code)
    ]


def combining_classes() -> dict[int, int]:
    classes = {}
    for code in _codes(MARK_BLOCKS):
        value = unicodedata.combining(chr(code))
        if value:
            classes[code] = value
    return classes


def decompositions() -> dict[int, list[int]]:
    table = {}
    for code in sorted(set(_codes(LETTER_BLOCKS))):
        mapping = unicodedata.decomposition(chr(code))
        if not mapping or mapping.startswith("<"):
            continue  # none, or a compatibility one
        table[code] = [int(part, 16) for part in mapping.split()]
    return table


def compositions(table: dict[int, list[int]]) -> dict[int, dict[int, int]]:
    pairs: dict[int, dict[int, int]] = {}
    for code, parts in table.items():
        if len(parts) != 2:
            continue
        first, second = parts
        if unicodedata.normalize("NFC", chr(first) + chr(second)) != chr(code):
            continue  # a composition exclusion
        pairs.setdefault(first, {})[second] = code
    return {first: dict(sorted(marks.items())) for first, marks in sorted(pairs.items())}


def _hex(code: int) -> str:
    return f"0x{code:04X}"


def generate() -> str:
    classes = combining_classes()
    table = decompositions()
    pairs = compositions(table)
    lines = [HEADER]
    lines.append("/// Canonical combining class of the combining marks covered.")
    lines.append("const nfcCombiningClasses = <int, int>{")
    lines += [f"  {_hex(code)}: {value}," for code, value in classes.items()]
    lines.append("};")
    lines.append("")
    lines.append("/// Canonical decomposition (one level) of the letters covered.")
    lines.append("const nfcDecompositions = <int, List<int>>{")
    lines += [
        f"  {_hex(code)}: [{', '.join(_hex(part) for part in parts)}],"
        for code, parts in table.items()
    ]
    lines.append("};")
    lines.append("")
    lines.append("/// Starter, then mark, to the letter NFC composes them to.")
    lines.append("const nfcCompositions = <int, Map<int, int>>{")
    for first, marks in pairs.items():
        entries = [f"{_hex(mark)}: {_hex(code)}" for mark, code in marks.items()]
        one_line = f"  {_hex(first)}: {{{', '.join(entries)}}},"
        if len(one_line) <= 80:  # as `dart format` lays it out
            lines.append(one_line)
            continue
        lines.append(f"  {_hex(first)}: {{")
        lines += [f"    {entry}," for entry in entries]
        lines.append("  },")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    if argv == ["--normalize"]:
        strings = json.load(sys.stdin)
        json.dump([unicodedata.normalize("NFC", text) for text in strings], sys.stdout)
        return 0
    generated = generate()
    if argv == ["--stdout"]:
        sys.stdout.write(generated)
        return 0
    if argv == ["--check"]:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != generated:
            print(f"{OUTPUT.relative_to(ROOT)} is stale: run python3 tool/passphrase_nfc.py")
            return 1
        return 0
    if argv:
        print(__doc__)
        return 2
    OUTPUT.write_text(generated, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
