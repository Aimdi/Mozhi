// Generated with qrcodegen 1.8.0 for Python (Project Nayuki's QR Code
// generator, MIT licence) in byte mode with `boostecl=False`, its automatic
// mask choice and the error correction level given. Every vector and every
// grid entry was also encoded with segno 1.6.1, an independent encoder,
// forcing the same mask, and the two matrices were identical. (segno 1.6.1
// adds a stray 0x00 codeword when the bit stream already ends on a byte
// boundary, which byte mode always does when padding follows; the check ran
// with that one function corrected to ISO/IEC 18004 section 7.4.10. For the
// small vectors all eight masks were compared.)
//
// Rows are top to bottom, `#` dark and `.` light, without the quiet zone.
// Grid digests: the first 16 hex digits of the SHA-256 of the rows as
// `0`/`1` strings joined by `\n`.

import 'package:mozhi/core/qr/qr_code.dart';

/// A small symbol compared module by module.
class QrVector {
  const new(
    this.text,
    this.errorCorrection,
    this.version,
    this.mask,
    this.rows,
  );

  final String text;
  final QrErrorCorrection errorCorrection;
  final int version;
  final int mask;
  final List<String> rows;
}

/// One version and level, compared by digest. [length] bytes of
/// [qrGridData].
class QrGridEntry {
  const new(
    this.errorCorrection,
    this.version,
    this.length,
    this.mask,
    this.digest,
  );

  final QrErrorCorrection errorCorrection;
  final int version;
  final int length;
  final int mask;
  final String digest;
}

/// The grid's data: [length] printable ASCII characters (`!` to `~`).
String qrGridData(int length) =>
    String.fromCharCodes(List.generate(length, (i) => 0x21 + (i * 7) % 94));

