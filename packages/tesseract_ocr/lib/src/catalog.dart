import 'dart:convert';

import 'package:meta/meta.dart';

// Where the language data is downloaded from (GitHub or a mirror).
export 'package:tesseract_ocr/src/model_source.dart';

/// The language data of one Tesseract language: `<code>.traineddata` from
/// tessdata_fast.
@immutable
final class TessdataLanguage {
  const new({
    required this.code,
    required this.name,
    required this.languages,
    required this.url,
    required this.size,
    required this.sha256,
  });

  factory fromJson(Map<String, Object?> json) {
    final code = _string(json, 'code');
    if (!isTesseractCode(code)) {
      throw FormatException('Invalid Tesseract code', code);
    }
    final url = Uri.tryParse(_string(json, 'url'));
    if (url == null || !url.isScheme('https') || url.host.isEmpty) {
      throw FormatException('Language data URLs must be https', json['url']);
    }
    if (url.pathSegments.lastOrNull != '$code.traineddata') {
      throw FormatException('The URL must name $code.traineddata', '$url');
    }
    final languages = json['languages'];
    if (languages is! List<Object?> ||
        languages.isEmpty ||
        languages.any((code) => code is! String || !_appCode.hasMatch(code))) {
      throw FormatException('Invalid languages for $code', languages);
    }
    return TessdataLanguage(
      code: code,
      name: _string(json, 'name'),
      languages: List.unmodifiable(languages.cast<String>()),
      url: url,
      size: _positiveInt(json, 'size'),
      sha256: _sha256(json, 'sha256'),
    );
  }

  /// Tesseract's code, e.g. `deu`, `chi_sim`.
  final String code;

  /// English name, e.g. `German`.
  final String name;

  /// The app's language codes this data reads (BCP 47 style, as in the
  /// app's language catalogue), best first, e.g. `[zh-TW, yue, lzh]`.
  final List<String> languages;

  /// Where the file is downloaded from by default (pinned to a
  /// tessdata_fast commit; see `tessdataDownloadUrls` for mirrors).
  final Uri url;

  /// Bytes of the file (download and on disk: it is not compressed).
  final int size;

  /// Lower-case hex SHA-256 of the file.
  final String sha256;

  /// The file name Tesseract loads: `<code>.traineddata`.
  String get fileName => '$code.traineddata';

  Map<String, Object?> toJson() => {
    'code': code,
    'name': name,
    'languages': languages,
    'url': url.toString(),
    'size': size,
    'sha256': sha256,
  };

  @override
  bool operator ==(Object other) =>
      other is TessdataLanguage &&
      other.code == code &&
      other.url == url &&
      other.size == size &&
      other.sha256 == sha256;

  @override
  int get hashCode => Object.hash(code, url, size, sha256);

  @override
  String toString() => 'TessdataLanguage($code)';
}

/// Whether [code] looks like a Tesseract language code as tessdata names
/// its files: three lower-case letters, optionally `_` and a three- or
/// four-letter variant (`eng`, `chi_sim`, `srp_latn`). The native library
/// accepts nothing else, so a code can only name a file directly in the
/// data directory.
bool isTesseractCode(String code) => _tesseractCode.hasMatch(code);

/// The downloadable language data: `assets/catalog.json`, generated by
/// `tool/tessdata_catalog.py` from tessdata_fast at one commit.
@immutable
final class TessdataCatalog {
  new(Iterable<TessdataLanguage> languages, {this.commit, this.source})
    : languages = List.unmodifiable(languages),
      _byCode = {for (final language in languages) language.code: language},
      _byAppCode = {
        for (final language in languages)
          for (final app in language.languages) _appKey(app): language,
      };

  factory fromJson(Map<String, Object?> json) {
    final schema = json['schemaVersion'];
    if (schema != supportedSchemaVersion) {
      throw FormatException('Unsupported catalog schema', schema);
    }
    final languages = json['languages'];
    if (languages is! List<Object?>) {
      throw const FormatException('Missing languages');
    }
    final parsed = [
      for (final language in languages)
        if (language is Map<String, Object?>)
          TessdataLanguage.fromJson(language)
        else
          throw FormatException('Invalid language', language),
    ];
    final codes = parsed.map((language) => language.code).toSet();
    if (codes.length != parsed.length) {
      throw const FormatException('Duplicate Tesseract codes');
    }
    final appCodes = <String>{};
    for (final language in parsed) {
      for (final app in language.languages) {
        if (!appCodes.add(_appKey(app))) {
          throw FormatException('App language mapped twice', app);
        }
      }
    }
    return TessdataCatalog(
      parsed,
      commit: json['commit'] as String?,
      source: json['source'] as String?,
    );
  }

  /// Parses `catalog.json`. Throws [FormatException] when it is invalid.
  factory parse(String source) {
    final json = jsonDecode(source);
    if (json is! Map<String, Object?>) {
      throw const FormatException('The catalog must be a JSON object');
    }
    return TessdataCatalog.fromJson(json);
  }

  static const supportedSchemaVersion = 1;

  /// Asset key of the bundled catalog.
  static const assetKey = 'packages/tesseract_ocr/assets/catalog.json';

  /// Every language, sorted by code.
  final List<TessdataLanguage> languages;

  /// The tessdata_fast commit the URLs are pinned to.
  final String? commit;

  /// The repository the data comes from.
  final String? source;

  final Map<String, TessdataLanguage> _byCode;
  final Map<String, TessdataLanguage> _byAppCode;

  /// The language with Tesseract [code] (`deu`), if any.
  TessdataLanguage? byCode(String code) => _byCode[code];

  /// The data that reads the app language [code] (`de`, `zh-TW`,
  /// `pt-BR`), if any.
  ///
  /// Matched case-insensitively (`_` = `-`): the full code first; else a
  /// code with a script subtag only matches that script without the region
  /// (`sr-Latn-RS` -> `sr-Latn`; `ms-Arab`, Jawi, matches nothing: the
  /// Malay data is Latin); else the primary subtag (`pt-BR` -> `pt`,
  /// `es-419` -> `es`). Chinese resolves by script or region: `zh`,
  /// `zh-Hans`, `zh-SG` -> Simplified; `zh-Hant`, `zh-HK`, `zh-MO` ->
  /// Traditional. A few legacy and alternative codes resolve too (`iw` ->
  /// Hebrew, `nb` -> Norwegian, `fil` -> Filipino, `in` -> Indonesian,
  /// `ji` -> Yiddish, `jw` -> Javanese, `kmr` -> Kurdish (Kurmanji),
  /// `prs` -> Persian).
  TessdataLanguage? forAppLanguage(String code) {
    final key = _appKey(code);
    if (key.isEmpty) return null;
    final direct = _byAppCode[key];
    if (direct != null) return direct;
    final parts = key.split('-');
    final primary = _aliases[parts.first] ?? parts.first;
    final script = parts.skip(1).where(_script.hasMatch);
    if (primary == 'zh') {
      final traditional = parts
          .skip(1)
          .any((part) => const {'hant', 'tw', 'hk', 'mo'}.contains(part));
      return _byAppCode[traditional ? 'zh-tw' : 'zh-cn'];
    }
    if (script.isNotEmpty) return _byAppCode['$primary-${script.first}'];
    return _byAppCode[primary];
  }

  /// Bytes of all language data.
  int get totalSize =>
      languages.fold(0, (sum, language) => sum + language.size);

  Map<String, Object?> toJson() => {
    'schemaVersion': supportedSchemaVersion,
    'source': ?source,
    'commit': ?commit,
    'languages': [for (final language in languages) language.toJson()],
  };

  static String _appKey(String code) =>
      code.trim().replaceAll('_', '-').toLowerCase();

  /// Legacy and alternative primary subtags -> the code in the catalog.
  static const _aliases = {
    'iw': 'he',
    'nb': 'no',
    'fil': 'tl',
    'in': 'id',
    'ji': 'yi',
    'jw': 'jv',
    'kmr': 'ku',
    'prs': 'fa',
  };
}

final _tesseractCode = RegExp(r'^[a-z]{3}(_[a-z]{3,4})?$');
final _appCode = RegExp(r'^[A-Za-z]{2,3}(-[A-Za-z0-9]{2,8})*$');
final _hexSha256 = RegExp(r'^[0-9a-f]{64}$');
final _script = RegExp(r'^[a-z]{4}$');

String _string(Map<String, Object?> json, String key) {
  final value = json[key];
  if (value is String && value.isNotEmpty) return value;
  throw FormatException('Missing "$key"', json);
}

int _positiveInt(Map<String, Object?> json, String key) {
  final value = json[key];
  if (value is int && value > 0) return value;
  throw FormatException('"$key" must be a positive integer', value);
}

String _sha256(Map<String, Object?> json, String key) {
  final value = json[key];
  if (value is String && _hexSha256.hasMatch(value)) return value;
  throw FormatException('"$key" must be a lower-case hex SHA-256', value);
}
