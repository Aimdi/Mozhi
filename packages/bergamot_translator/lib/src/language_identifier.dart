/// A small, dependency-free language identifier for
/// [OfflineTranslator.identifyLanguage] (ML Kit's identifier is not
/// available without Google code).
///
/// It answers only when it is confident and returns null otherwise (the
/// app then asks for the source language):
/// * scripts used by one supported language: Hangul (`ko`), kana (`ja`),
///   Han only (`zh`), Greek, Hebrew, Thai, Bengali, Gujarati, Kannada,
///   Malayalam, Tamil, Telugu;
/// * Arabic and Cyrillic scripts by their language-specific letters
///   (`ur`, `fa`, `ug`, `ar`; `uk`, `be`, `sr`, `bg`, `ru`);
/// * Latin script by function words and diacritics of 30 languages, when
///   one clearly wins (texts of a few words are often undetermined).
///
/// This is a heuristic, not a statistical model. A real identifier (e.g.
/// CLD2 compiled into the native library) is a possible follow-up.
abstract final class LanguageIdentifier {
  /// BCP-47 code of [text]'s language, or null when undetermined.
  static String? identify(String text) {
    final counts = <_Script, int>{};
    var letters = 0;
    for (final rune in text.runes) {
      final script = _scriptOf(rune);
      if (script == null) continue;
      letters++;
      counts[script] = (counts[script] ?? 0) + 1;
    }
    if (letters == 0) return null;
    final (script, count) = counts.entries
        .map((e) => (e.key, e.value))
        .reduce((a, b) => a.$2 >= b.$2 ? a : b);
    final kana = counts[_Script.kana] ?? 0;
    final han = counts[_Script.han] ?? 0;
    // Japanese mixes kana and kanji; any real amount of kana decides it.
    if (kana > 0 && kana * 10 >= (kana + han)) return 'ja';
    if (count * 10 < letters * 6) return null;
    return switch (script) {
      _Script.hangul => 'ko',
      _Script.kana => 'ja',
      _Script.han => 'zh',
      _Script.greek => 'el',
      _Script.hebrew => 'he',
      _Script.thai => 'th',
      _Script.bengali => 'bn',
      _Script.gujarati => 'gu',
      _Script.kannada => 'kn',
      _Script.malayalam => 'ml',
      _Script.tamil => 'ta',
      _Script.telugu => 'te',
      // Hindi and Marathi share Devanagari.
      _Script.devanagari => null,
      _Script.arabic => _arabicScript(text),
      _Script.cyrillic => _cyrillic(text),
      _Script.latin => _latin(text),
    };
  }

  static String _arabicScript(String text) {
    // Letters specific to one language (checked in this order).
    if (_containsAny(text, 'ېۆۇۈۋە')) return 'ug';
    if (_containsAny(text, 'ٹڈڑںےۓ')) return 'ur';
    if (_containsAny(text, 'پچژگ')) return 'fa';
    return 'ar';
  }

  static String? _cyrillic(String text) {
    final lower = text.toLowerCase();
    if (_containsAny(lower, 'ђјљњћџ')) return 'sr';
    if (_containsAny(lower, 'ў')) return 'be';
    if (_containsAny(lower, 'їєґ')) return 'uk';
    if (_containsAny(lower, 'і')) return null; // be or uk
    if (_containsAny(lower, 'ыэё')) return 'ru';
    if (_containsAny(lower, 'ъ')) {
      // Bulgarian uses ъ as a vowel, Russian rarely (and has ы).
      return 'bg';
    }
    return 'ru';
  }

  static String? _latin(String text) {
    final words = _words
        .allMatches(text.toLowerCase())
        .map((m) => m.group(0)!)
        .toList();
    if (words.isEmpty) return null;
    final scores = <String, double>{};
    for (final MapEntry(key: language, value: list) in _functionWords.entries) {
      var score = 0.0;
      for (final word in words) {
        if (list.contains(word)) score++;
      }
      final marks = _diacritics[language];
      if (marks != null) {
        for (final rune in text.toLowerCase().runes) {
          final mark = String.fromCharCode(rune);
          if (marks.contains(mark)) {
            score += _strongMarks.contains(mark) ? 1 : 0.5;
          }
        }
      }
      if (score > 0) scores[language] = score;
    }
    if (scores.isEmpty) return null;
    final ranked = scores.entries.toList()
      ..sort((a, b) => b.value.compareTo(a.value));
    final best = ranked.first;
    final second = ranked.length > 1 ? ranked[1].value : 0.0;
    // At least two hits and a clear margin over the runner-up.
    if (best.value < 2 || best.value < second * 1.5) return null;
    return best.key;
  }

  static bool _containsAny(String text, String letters) =>
      letters.runes.any((rune) => text.contains(String.fromCharCode(rune)));

  static final _words = RegExp(r"[\p{L}']+", unicode: true);

  static _Script? _scriptOf(int rune) {
    if (rune < 0x41) return null;
    if ((rune >= 0x41 && rune <= 0x5A) ||
        (rune >= 0x61 && rune <= 0x7A) ||
        (rune >= 0xC0 && rune <= 0x24F && rune != 0xD7 && rune != 0xF7) ||
        (rune >= 0x1E00 && rune <= 0x1EFF)) {
      return _Script.latin;
    }
    for (final (start, end, script) in _ranges) {
      if (rune >= start && rune <= end) return script;
    }
    return null;
  }

