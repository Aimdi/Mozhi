/// Static catalogue of world languages for AI engines (which can translate
/// between any pair). ~290 entries: every Google Translate language plus
/// common regional variants (pt-BR, pt-PT, zh-CN/zh-Hans, zh-TW/zh-Hant,
/// yue, es-419, fr-CA, en-GB, en-US, sr-Latn, ckb, several Arabic
/// varieties) and languages LLMs handle well (Latin, Ancient Greek,
/// Classical Chinese, Toki Pona, ...), each with English [Language.name] and
/// [Language.nativeName]. Sorted by English name. Never contains `auto`.
abstract final class LanguageCatalog {
  static List<Language> get all => _languages;

  static final Map<String, Language> _byCode = {
    for (final language in _languages) language.code.toLowerCase(): language,
  };

  static final Map<String, Language> _byName = {
    for (final language in _languages) _nameKey(language.name): language,
  };

  /// Exact-code lookup after normalisation (case-insensitive, `_` -> `-`).
  ///
  /// Legacy and engine-specific codes resolve too (`iw` -> Hebrew, `zh` ->
  /// Chinese (Simplified), `fr-FR` -> French); see
  /// [LanguageMatcher.normalize].
  static Language? byCode(String code) {
    final key = code.trim().replaceAll('_', '-').toLowerCase();
    if (key.isEmpty) return null;
    return _byCode[key] ?? _byCode[LanguageMatcher.normalize(code).toLowerCase()];
  }

  /// Case-insensitive lookup by English name (`"japanese"` -> Japanese).
  /// Punctuation and spacing are ignored.
  static Language? byName(String name) {
    final key = _nameKey(name);
    return key.isEmpty ? null : _byName[key];
  }

  /// English name for [code], or [code] itself when unknown.
  static String nameOf(String code) => byCode(code)?.name ?? code;

  /// Popular suggestions for custom AI targets, e.g. "Pirate speak",
